package gameshelf.persistence;

import java.sql.Connection;
import java.sql.SQLException;
import java.sql.Statement;

/**
 * Esquema de la base de datos. Todo vive en la misma base: las imágenes se guardan como BLOB en la tabla "imagen",
 * así que al copiar la base se copian también las imágenes.
 */
final class Esquema {

    private static final String[] SENTENCIAS = {
        "CREATE TABLE IF NOT EXISTS usuario ("
            + " id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,"
            + " nombre VARCHAR_IGNORECASE(30) NOT NULL UNIQUE,"
            + " rol VARCHAR(10) NOT NULL,"
            + " salt VARCHAR(64) NOT NULL,"
            + " hash VARCHAR(128) NOT NULL)",

        "CREATE TABLE IF NOT EXISTS imagen ("
            + " nombre VARCHAR(80) PRIMARY KEY,"
            + " tipo VARCHAR(10) NOT NULL,"
            + " datos BLOB NOT NULL)",

        "CREATE TABLE IF NOT EXISTS videojuego ("
            + " id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,"
            + " nombre VARCHAR(100) NOT NULL,"
            + " plataforma VARCHAR(700) DEFAULT '' NOT NULL,"
            + " genero VARCHAR(700) DEFAULT '' NOT NULL,"
            + " desarrollador VARCHAR(700) DEFAULT '' NOT NULL,"
            + " anio INT DEFAULT 0 NOT NULL,"
            + " fecha_creacion TIMESTAMP NOT NULL,"
            + " creado_por VARCHAR(30) DEFAULT '' NOT NULL,"
            + " imagen VARCHAR(80) DEFAULT '' NOT NULL)",

        "CREATE TABLE IF NOT EXISTS seguimiento ("
            + " usuario_id INT NOT NULL,"
            + " videojuego_id INT NOT NULL,"
            + " estado VARCHAR(12),"
            + " horas_jugadas DOUBLE PRECISION,"
            + " favorito BOOLEAN DEFAULT FALSE NOT NULL,"
            + " notas VARCHAR(2000) DEFAULT '' NOT NULL,"
            + " PRIMARY KEY (usuario_id, videojuego_id),"
            + " FOREIGN KEY (usuario_id) REFERENCES usuario(id) ON DELETE CASCADE,"
            + " FOREIGN KEY (videojuego_id) REFERENCES videojuego(id) ON DELETE CASCADE)",

        "CREATE TABLE IF NOT EXISTS calificacion ("
            + " usuario_id INT NOT NULL,"
            + " videojuego_id INT NOT NULL,"
            + " puntuacion INT NOT NULL CHECK (puntuacion BETWEEN 1 AND 10),"
            + " fecha TIMESTAMP NOT NULL,"
            + " PRIMARY KEY (usuario_id, videojuego_id),"
            + " FOREIGN KEY (usuario_id) REFERENCES usuario(id) ON DELETE CASCADE,"
            + " FOREIGN KEY (videojuego_id) REFERENCES videojuego(id) ON DELETE CASCADE)"
    };

    private Esquema() {
    }

    static void crear(Connection conexion) throws SQLException {
        try (Statement st = conexion.createStatement()) {
            for (String sql : SENTENCIAS) {
                st.execute(sql);
            }
        }
    }
}
